export const normalize = (s) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
export function searchProducts(products, query) {
  const q = normalize(query).trim();
  if (!q) return products;
  const stop = new Set([
    "de",
    "da",
    "do",
    "o",
    "a",
    "um",
    "uma",
    "para",
    "por",
    "com",
    "preciso",
    "quero",
    "coisa",
    "peca",
    "meu",
    "minha",
    "na",
    "no",
    "e",
    "mm",
  ]);
  const tokens = q.split(/\W+/).filter((t) => t.length > 1 && !stop.has(t));
  return products
    .map((p) => {
      const corpus = normalize(
        [p.name, p.id, p.category, p.attributes, ...p.synonyms].join(" "),
      );
      let score = tokens.reduce((s, t) => s + (corpus.includes(t) ? 1 : 0), 0);
      if (p.synonyms.some((s) => q.includes(normalize(s)))) score += 4;
      if (q === p.id) score += 20;
      const sizes = q.match(/\b(25|50|127|220|10|20)\b/g);
      if (sizes && sizes.some((s) => !normalize(p.attributes).includes(s)))
        score -= 3;
      return { p, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((x) => x.p);
}
export function isWalkable(p, blocked = []) {
  return (
    p.x >= 0 &&
    p.x < 13 &&
    p.y >= 0 &&
    p.y < 11 &&
    !(storeBays.some((b) => b.x === p.x) && [2, 3, 4, 6, 7, 8].includes(p.y)) &&
    !blocked.some((b) => b.x === p.x && b.y === p.y)
  );
}
export function shortestPath(start, end, blocked = []) {
  if (!isWalkable(start, blocked) || !isWalkable(end, blocked)) return [];
  const key = (p) => `${p.x},${p.y}`;
  const q = [start],
    seen = new Set([key(start)]),
    prev = new Map();
  for (let i = 0; i < q.length; i++) {
    const p = q[i];
    if (key(p) === key(end)) {
      const path = [p];
      while (key(path[0]) !== key(start)) path.unshift(prev.get(key(path[0])));
      return path;
    }
    for (const [dx, dy] of [
      [1, 0],
      [-1, 0],
      [0, 1],
      [0, -1],
    ]) {
      const n = { x: p.x + dx, y: p.y + dy };
      if (isWalkable(n, blocked) && !seen.has(key(n))) {
        seen.add(key(n));
        prev.set(key(n), p);
        q.push(n);
      }
    }
  }
  return [];
}
export function optimizeRoute(start, items, blocked = []) {
  const targets = items.slice(0, 10);
  if (!targets.length) return { items: [], path: [], distance: 0 };
  const points = [start, ...targets],
    paths = points.map((a) => points.map((b) => shortestPath(a, b, blocked)));
  if (paths[0].some((p) => !p.length))
    throw new Error("Há produtos sem acesso. Revise os bloqueios do mapa.");
  const n = targets.length,
    dp = new Map();
  for (let i = 0; i < n; i++)
    dp.set(`${1 << i}:${i}`, { d: paths[0][i + 1].length - 1, order: [i] });
  for (let mask = 1; mask < 1 << n; mask++)
    for (let last = 0; last < n; last++) {
      const curr = dp.get(`${mask}:${last}`);
      if (!curr) continue;
      for (let next = 0; next < n; next++)
        if (!(mask & (1 << next))) {
          const k = `${mask | (1 << next)}:${next}`,
            d = curr.d + paths[last + 1][next + 1].length - 1;
          if (!dp.has(k) || dp.get(k).d > d)
            dp.set(k, { d, order: [...curr.order, next] });
        }
    }
  const best = Array.from(dp)
    .filter(([k]) => k.startsWith(`${(1 << n) - 1}:`))
    .map(([, v]) => v)
    .sort((a, b) => a.d - b.d)[0];
  let at = 0;
  const path = [];
  for (const i of best.order) {
    path.push(...paths[at][i + 1].slice(path.length ? 1 : 0));
    at = i + 1;
  }
  return {
    items: best.order.map((i) => targets[i]),
    path,
    distance: best.d * 2,
  };
}
